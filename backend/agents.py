def get_available_groq_models():
    """
    Fetches the currently active model IDs on this Groq account.
    Caches the list in memory.
    """
    global _available_models_cache
    if _available_models_cache is not None:
        return _available_models_cache
    if not client:
        return set()
    try:
        models = client.models.list()
        _available_models_cache = {m.id for m in models.data if getattr(m, 'active', True)}
        return _available_models_cache
    except Exception as e:
        print(f"Warning: Could not fetch Groq models list ({e}). Will try candidates sequentially.")
        return set()

def get_best_model(requested_model: str = "") -> str:
    """
    Returns the best available active model on Groq.
    """
    global _active_model
    available = get_available_groq_models()
    
    if requested_model and (not available or requested_model in available):
        return requested_model
        
    if _active_model and (not available or _active_model in available):
        return _active_model
        
    for candidate in CANDIDATE_MODELS:
        if not available or candidate in available:
            _active_model = candidate
            return _active_model
            
    return "groq/compound-mini"

def strip_internal_thinking(text: str) -> str:
    """
    Strips internal thinking tokens (<think>...</think>), reasoning blocks, 
    scratchpad meta-planning notes, and prompt template leaks.
    Preserves valid References / Sources lists for citation extraction.
    """
    if not text:
        return ""
    if "</think>" in text.lower():
        parts = re.split(r'</think>', text, flags=re.IGNORECASE)
        cleaned = parts[-1].strip()
    elif "<think>" in text.lower():
        cleaned = re.sub(r'<think>', '', text, flags=re.IGNORECASE).strip()
    else:
        cleaned = text.strip()

    cleaned = re.sub(r'^(?:Thinking Process|Thought Process|Reasoning):[\s\S]*?\n\n', '', cleaned.strip(), flags=re.IGNORECASE)
    cleaned = re.sub(r'(?:^\s*\d+\.\s*\n+)?\s*\*{1,2}(?:Review Transcript|Identify Key Points|Goal for Closing|Agent [AB]\'s (?:Core|Previous) Arguments|Drafting Notes|Strategy|Plan|Debate Plan)[^*]*\*{1,2}[\s\S]*?(?=\n\n[A-Z0-9]|\Z)', '', cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r'\*+(?:Word Count|Constraint|Cutting|Deconstruct)[^*]*\*+[\s\S]*?(?=\n\n|\Z)', '', cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r'\[(?:Source Name|Source|Source Title)\]\(exact URL from research\)', '', cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r'\(exact URL from research\)', '', cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r'\[exact URL from research\]', '', cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r'<\s*\[\s*(\d+)\s*\]\s*>', r'[\1]', cleaned)
    cleaned = re.sub(r'[【\u3010][^】\u3011]*[】\u3011]', '', cleaned)
    cleaned = re.sub(r'^\s*\d+\.\s*\n+', '', cleaned)
    return cleaned.strip()

def format_and_dedup_turn(text: str) -> str:
    """
    Cleans thinking tokens and deduplicates identical or repetitive paragraphs
    while strictly preserving references.
    """
    if not text:
        return ""
    cleaned = strip_internal_thinking(text)
    
    # Extract references section if present
    ref_match = re.search(r'(?:\n+|^)(?:References?|Sources?|Works Cited|Bibliography):\s*\n([\s\S]*)$', cleaned, flags=re.IGNORECASE)
    ref_block = ""
    main_text = cleaned
    if ref_match:
        ref_block = ref_match.group(1).strip()
        main_text = cleaned[:ref_match.start()].strip()
        
    # Deduplicate repetitive paragraphs generated by LLMs
    paras = [p.strip() for p in re.split(r'\n\s*\n', main_text) if p.strip()]
    unique_paras = []
    seen = set()
    for p in paras:
        # Create a normalized signature key
        norm_key = re.sub(r'[^a-zA-Z0-9]', '', p.lower())[:80]
        if norm_key and norm_key not in seen:
            seen.add(norm_key)
            unique_paras.append(p)
            
    final_main = "\n\n".join(unique_paras) if unique_paras else main_text
    
    if ref_block:
        return f"{final_main}\n\nReferences:\n{ref_block}"
    return final_main

def clean_and_parse_json(text: str):
    """
    Cleans markdown code blocks, thinking tags, and extracts JSON safely from LLM outputs.
    """
    clean_text = strip_internal_thinking(text)
    if clean_text.startswith("```json"):
        clean_text = clean_text[7:]
    elif clean_text.startswith("```"):
        clean_text = clean_text[3:]
    if clean_text.endswith("```"):
        clean_text = clean_text[:-3]
    clean_text = clean_text.strip()
    
    try:
        return json.loads(clean_text)
    except json.JSONDecodeError:
        match_obj = re.search(r'(\{[\s\S]*\}|\[[\s\S]*\])', clean_text)
        if match_obj:
            try:
                return json.loads(match_obj.group(1))
            except json.JSONDecodeError:
                pass
        raise Exception(f"Failed to parse JSON from output: {text[:250]}")

# ─── Multi-Provider LLM Callers ──────────────────────────────

def call_gemini_api(prompt: str, temperature: float = 0.7, json_mode: bool = False, max_tokens: int = 2048) -> str:
    """
    Calls Google Gemini API (Gemini 2.5 Flash / 3.6 Flash / Balanced Mode).
    """
    if not settings.GEMINI_API_KEY:
        raise Exception("GEMINI_API_KEY is not configured")
        
    models = ["gemini-3.6-flash", "gemini-flash-latest", "gemini-2.5-flash", "gemma-4-31b-it"]
    cur_prompt = prompt
    if json_mode and "json" not in cur_prompt.lower():
        cur_prompt += "\n\nPlease ensure your output is strictly a valid JSON object."
        
    last_err = None
    for m in models:
        try:
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{m}:generateContent?key={settings.GEMINI_API_KEY}"
            payload = {
                "contents": [{"parts": [{"text": cur_prompt}]}],
                "generationConfig": {
                    "temperature": temperature,
                    "maxOutputTokens": max_tokens
                }
            }
            if json_mode:
                payload["generationConfig"]["responseMimeType"] = "application/json"
            r = requests.post(url, json=payload, timeout=25)
            if r.status_code == 200:
                res = r.json()
                raw = res["candidates"][0]["content"]["parts"][0]["text"]
                return strip_internal_thinking(raw)
            else:
                last_err = f"Status {r.status_code}: {r.text[:120]}"
        except Exception as e:
            last_err = str(e)
            continue
    raise Exception(f"Gemini generation failed: {last_err}")


def call_oxalpha_api(prompt: str, temperature: float = 0.7, json_mode: bool = False, max_tokens: int = 2048) -> str:
    """
    Calls OxAlpha (Deep Reasoning Mode) via OpenRouter / Stealth engine.
    """
    if not settings.OPENROUTER_API_KEY:
        raise Exception("OPENROUTER_API_KEY is not configured for OxAlpha")
        
    models = ["stealth/ox-alpha", "deepseek/deepseek-chat", "meta-llama/llama-3.3-70b-instruct", "qwen/qwen-2.5-72b-instruct"]
    cur_prompt = prompt
    if json_mode and "json" not in cur_prompt.lower():
        cur_prompt += "\n\nPlease ensure your output is strictly a valid JSON object."
        
    headers = {
        "Authorization": f"Bearer {settings.OPENROUTER_API_KEY}",
        "Content-Type": "application/json",
        "HTTP-Referer": "https://arguforge.ai",
        "X-Title": "ArguForge AI Arena"
    }
    last_err = None
    for m in models:
        try:
            payload = {
                "model": m,
                "messages": [{"role": "user", "content": cur_prompt}],
                "temperature": temperature,
                "max_tokens": max_tokens
            }
            if json_mode:
                payload["response_format"] = {"type": "json_object"}
            r = requests.post("https://openrouter.ai/api/v1/chat/completions", headers=headers, json=payload, timeout=25)
            if r.status_code == 200:
                res = r.json()
                raw = res["choices"][0]["message"]["content"]
                return strip_internal_thinking(raw)
            else:
                last_err = f"Status {r.status_code}: {r.text[:120]}"
        except Exception as e:
            last_err = str(e)
            continue
    raise Exception(f"OxAlpha generation failed: {last_err}")


def call_openrouter_api(model_slug: str, prompt: str, temperature: float = 0.7, json_mode: bool = False, max_tokens: int = 2048) -> str:
    """
    Calls user-specified custom model via OpenRouter (Custom Mode).
    """
    if not settings.OPENROUTER_API_KEY:
        raise Exception("OPENROUTER_API_KEY is not configured")
        
    cur_prompt = prompt
    if json_mode and "json" not in cur_prompt.lower():
        cur_prompt += "\n\nPlease ensure your output is strictly a valid JSON object."
        
    headers = {
        "Authorization": f"Bearer {settings.OPENROUTER_API_KEY}",
        "Content-Type": "application/json",
        "HTTP-Referer": "https://arguforge.ai",
        "X-Title": "ArguForge AI Arena"
    }
    slug = (model_slug or "").strip() or "meta-llama/llama-3.3-70b-instruct"
    payload = {
        "model": slug,
        "messages": [{"role": "user", "content": cur_prompt}],
        "temperature": temperature,
        "max_tokens": max_tokens
    }
    if json_mode:
        payload["response_format"] = {"type": "json_object"}
        
    r = requests.post("https://openrouter.ai/api/v1/chat/completions", headers=headers, json=payload, timeout=30)
    if r.status_code == 200:
        res = r.json()
        raw = res["choices"][0]["message"]["content"]
        return strip_internal_thinking(raw)
    raise Exception(f"OpenRouter error for model '{slug}': Status {r.status_code} - {r.text[:120]}")


def call_groq_api(
    model_name: str = "", 
    prompt: str = "", 
    temperature: float = 0.7, 
    json_mode: bool = False, 
    max_retries: int = 3,
    max_tokens: int = 2048
) -> str:
    """
    Calls the Groq API (Lightning / Speed Mode) with automatic candidate fallback.
    """
    global _active_model
    if not client:
        raise Exception("Groq client not initialized")
        
    best_initial = get_best_model(model_name)
    models_to_try = [best_initial] + [m for m in CANDIDATE_MODELS if m != best_initial]
    
    last_exception = None
    for current_model in models_to_try:
        delay = 0.8
        for attempt in range(max_retries):
            try:
                cur_prompt = prompt
                if json_mode and "json" not in cur_prompt.lower():
                    cur_prompt += "\n\nPlease ensure your output is in valid JSON format."
                    
                completion = client.chat.completions.create(
                    model=current_model,
                    messages=[{"role": "user", "content": cur_prompt}],
                    temperature=temperature,
                    response_format={"type": "json_object"} if json_mode else None,
                    max_tokens=max_tokens
                )
                _active_model = current_model
                raw_content = completion.choices[0].message.content or ""
                return strip_internal_thinking(raw_content)
            except Exception as e:
                err_str = str(e).lower()
                last_exception = e
                if "model_not_found" in err_str or "404" in err_str or "does not exist" in err_str or "decommissioned" in err_str:
                    break
                elif "413" in err_str or "too_large" in err_str:
                    break
                elif "429" in err_str or "rate limit" in err_str:
                    time.sleep(0.5)
                    break
                elif "response_format" in err_str or "json_object" in err_str:
                    try:
                        text_prompt = cur_prompt + "\n\nCRITICAL: Output ONLY a valid JSON object without conversation."
                        completion = client.chat.completions.create(
                            model=current_model,
                            messages=[{"role": "user", "content": text_prompt}],
                            temperature=temperature,
                            max_tokens=max_tokens
                        )
                        _active_model = current_model
                        raw_content = completion.choices[0].message.content or ""
                        return strip_internal_thinking(raw_content)
                    except Exception as sub_e:
                        last_exception = sub_e
                        break
                else:
                    time.sleep(delay)
                    
    raise Exception(f"All Groq models failed. Last error: {last_exception}")


def generate_content_with_retry(
    model_name: str = "", 
    prompt: str = "", 
    temperature: float = 0.7, 
    json_mode: bool = False, 
    max_retries: int = 3,
    max_tokens: int = 2048,
    provider: str = "gemini",
    custom_model: str = ""
) -> str:
    """
    Unified multi-model dispatcher routing requests through Groq, Gemini 2.5 Flash, 
    OxAlpha, or OpenRouter with automatic provider fallback for zero downtime.
    """
    if MOCK_MODE:
        return "{}"
        
    provider_norm = (provider or "gemini").lower().strip()
    
    # 1. Gemini (Default / Balanced)
    if provider_norm == "gemini":
        try:
            return call_gemini_api(prompt=prompt, temperature=temperature, json_mode=json_mode, max_tokens=max_tokens)
        except Exception as e:
            print(f"Gemini dispatch warning ({e}). Falling back to Groq...")
            try:
                return call_groq_api(model_name=model_name, prompt=prompt, temperature=temperature, json_mode=json_mode, max_retries=max_retries, max_tokens=max_tokens)
            except Exception:
                return call_oxalpha_api(prompt=prompt, temperature=temperature, json_mode=json_mode, max_tokens=max_tokens)
                
    # 2. Groq (Lightning / Speed)
    elif provider_norm == "groq":
        try:
            return call_groq_api(model_name=model_name, prompt=prompt, temperature=temperature, json_mode=json_mode, max_retries=max_retries, max_tokens=max_tokens)
        except Exception as e:
            print(f"Groq dispatch warning ({e}). Falling back to Gemini...")
            return call_gemini_api(prompt=prompt, temperature=temperature, json_mode=json_mode, max_tokens=max_tokens)
            
    # 3. OxAlpha (Deep Reasoning)
    elif provider_norm == "oxalpha":
        try:
            return call_oxalpha_api(prompt=prompt, temperature=temperature, json_mode=json_mode, max_tokens=max_tokens)
        except Exception as e:
            print(f"OxAlpha dispatch warning ({e}). Falling back to Gemini...")
            return call_gemini_api(prompt=prompt, temperature=temperature, json_mode=json_mode, max_tokens=max_tokens)
            
    # 4. OpenRouter (Custom Mode)
    elif provider_norm == "openrouter":
        try:
            return call_openrouter_api(model_slug=custom_model, prompt=prompt, temperature=temperature, json_mode=json_mode, max_tokens=max_tokens)
        except Exception as e:
            print(f"OpenRouter dispatch warning ({e}). Falling back to Gemini...")
            return call_gemini_api(prompt=prompt, temperature=temperature, json_mode=json_mode, max_tokens=max_tokens)
            
    # Default: Gemini
    else:
        return call_gemini_api(prompt=prompt, temperature=temperature, json_mode=json_mode, max_tokens=max_tokens)

# ─── Topic Stances ───────────────────────────────────────────

def parse_topic_stances(topic: str, research_context: str = "", provider: str = "gemini", custom_model: str = "") -> dict:
    """
    Generates opposing stances for Agent A and Agent B based on the topic and optional research.
    """
    if MOCK_MODE:
        return {
            "stance_a": f"Argues in favor of: '{topic}'.",
            "stance_b": f"Argues against: '{topic}'."
        }

    research_section = ""
    if research_context:
        research_section = f"""
    REAL-WORLD RESEARCH AND FACTS ABOUT THE TOPIC:
    {research_context}
    
    Ensure the stances are factually grounded and aligned with the actual meaning and context of the topic as shown in the research above.
    """

    prompt = f"""
    You are a debate topic parser.
    Given this debate topic: "{topic}"
    
    {research_section}
    
    Define two opposing stances for Agent A (who argues in favor or supports the topic/stance 1) 
    and Agent B (who argues against or supports stance 2).
    Keep each stance simple, specific, and clear (1 sentence each).
    
    Your output MUST be a JSON object with the keys "stance_a" and "stance_b".
    Do not add extra commentary.
    """
    try:
        response_text = generate_content_with_retry("groq/compound-mini", prompt, temperature=0.2, json_mode=True, provider=provider, custom_model=custom_model)
        return clean_and_parse_json(response_text)
    except Exception as e:
        print(f"Error parsing topic stances: {e}")
        return {
            "stance_a": f"Argue in favor of the statement: '{topic}'",
            "stance_b": f"Argue against the statement: '{topic}'"
        }

# ─── Debate Turn Generation (Grounded with Citations) ────────

def generate_debate_turn(
    topic: str, 
    stance: str, 
    agent_name: str, 
    history: list[dict], 
    round_number: int, 
    temperature: float,
    research_context: str = "",
    provider: str = "gemini",
    custom_model: str = ""
) -> str:
    """
    Generates a turn for a debating agent, strictly grounded in provided research context.
    The agent MUST cite sources inline using markdown link syntax.
    """
    if MOCK_MODE:
        return f"{agent_name} argues for round {round_number} about {topic}. According to [Reuters](https://www.reuters.com/example), the data supports the stance: {stance}."

    # Map round numbers to names
    round_names = {
        1: "Opening Statement",
        2: "Rebuttal Round 1",
        3: "Rebuttal Round 2",
        4: "Rebuttal Round 3",
        5: "Closing Statement"
    }
    round_name = round_names.get(round_number, f"Round {round_number}")
    
    # Format the transcript history
    history_text = ""
    for turn in history:
        history_text += f"{turn['agent']}: {turn['content']}\n\n"
        
    opposing_agent = "Agent B" if agent_name == "Agent A" else "Agent A"
    
    research_section = ""
    if research_context:
        research_section = f"""
    ══════════════════════════════════════════
    VERIFIED RESEARCH SOURCES (EVIDENCE POOL):
    ══════════════════════════════════════════
    {research_context}
    ══════════════════════════════════════════
    
    CITATION RULES:
    • When asserting factual statistics, events, data, or findings from the evidence above, attach a bracketed number [1], [2] directly after the claim sentence.
    • At the bottom of your turn, provide the exact corresponding references in this format:
      References:
      [1] Source Name: Title - URL
      [2] Source Name: Title - URL
    """
    else:
        research_section = """
    CITATION RULES:
    • Ground arguments in factual logic and real-world evidence.
    • Use bracketed reference numbers [1], [2] after factual claims, and list them under 'References:' at the bottom.
    """

    prompt = f"""
    You are a professional debater in a formal Fact-Checked ArguForge AI debate.
    
    Topic: {topic}
    Your Name: {agent_name}
    Your Stance: {stance}
    Current Phase: {round_name}
    
    {research_section}
    
    DEBATE TRANSCRIPT SO FAR:
    {history_text if history_text else "[Debate is just starting. This is the first turn.]"}
    
    INSTRUCTIONS:
    1. Argue strongly and in good faith. Stick to your assigned stance.
    2. Write 110-150 words in 1-2 powerful, coherent spoken paragraphs.
    3. If this is a rebuttal round, directly address {opposing_agent}'s previous argument.
    4. For factual claims, cite the evidence number in the paragraph (e.g. "...according to market reports [1]...").
    5. List all cited references at the bottom under a "References:" heading.
    6. CRITICAL: NEVER repeat sentences or duplicate paragraphs.
    7. ABSOLUTELY FORBIDDEN: Do not write thinking outlines, "Review Transcript", "Identify Key Points", bulleted planning notes, or meta-commentary. Output ONLY the speech paragraphs followed by the References list.
    
    Begin your response directly with your speech arguments. No salutations or preambles.
    """
    
    try:
        raw = generate_content_with_retry("groq/compound-mini", prompt, temperature=temperature, provider=provider, custom_model=custom_model)
        return format_and_dedup_turn(raw)
    except Exception as e:
        print(f"Error generating debate turn for {agent_name} (Round {round_number}): {e}")
        return f"{agent_name} argues for round {round_number} regarding '{topic}'. In accordance with the stance '{stance}', the empirical arguments and logical considerations demonstrate significant merits that must be addressed."

# ─── Factcheck Analysis Mode ─────────────────────────────────

def generate_factcheck_analysis(
    topic: str, 
    research_context: str = "", 
    stance_preference: str = "both",
    provider: str = "gemini",
    custom_model: str = ""
) -> dict:
    """
    Generates a structured fact-check analysis focusing on the user's stance preference:
    FOR case, AGAINST case, or BOTH, alongside a balanced/contextual VERDICT.
    All claims must be grounded in the provided research context with inline citations.
    """
    if MOCK_MODE:
        return {
            "for_case": f"The evidence supports '{topic}'. [Reuters](https://reuters.com) reports positive trends.",
            "against_case": f"Critics argue against '{topic}'. [BBC](https://bbc.com) highlights concerns.",
            "verdict": f"The evidence is mixed. Both sides present valid points grounded in credible sources."
        }
    
    research_section = ""
    if research_context:
        research_section = f"""
    ══════════════════════════════════════════
    VERIFIED RESEARCH SOURCES (PRIMARY EVIDENCE POOL):
    ══════════════════════════════════════════
    {research_context}
    ══════════════════════════════════════════
    """

    # Customize instructions and outputs based on stance preference
    if stance_preference == "for":
        sections_instruction = """
    Produce a structured analysis with TWO sections:
    1. "for_case" — The strongest arguments SUPPORTING the topic. 
       Write a detailed, comprehensive analysis of 200-300 words containing specific facts, figures, dates, and percentages.
       Cite factual claims with [Source Name](URL).
       
    2. "verdict" — Your balanced analytical verdict weighing the evidence supporting the topic.
       Write 100-150 words summarizing the strength of the supporting evidence.
        """
        output_format = """
    Output MUST be a JSON object:
    {
      "for_case": "...",
      "verdict": "..."
    }
        """
    elif stance_preference == "against":
        sections_instruction = """
    Produce a structured analysis with TWO sections:
    1. "against_case" — The strongest arguments OPPOSING the topic.
       Write a detailed, comprehensive analysis of 200-300 words containing specific facts, figures, dates, and percentages.
       Cite factual claims with [Source Name](URL).
       
    2. "verdict" — Your balanced analytical verdict weighing the evidence opposing the topic.
       Write 100-150 words summarizing the strength of the opposing evidence.
        """
        output_format = """
    Output MUST be a JSON object:
    {
      "against_case": "...",
      "verdict": "..."
    }
        """
    else:  # both
        sections_instruction = """
    Produce a structured analysis with THREE sections:
    1. "for_case" — The strongest arguments SUPPORTING the topic. 
       Write 180-250 words. Cite factual claims with [Source Name](URL).
       
    2. "against_case" — The strongest arguments OPPOSING the topic.
       Write 180-250 words. Cite factual claims with [Source Name](URL).
       
    3. "verdict" — Your balanced analytical verdict weighing both sides.
       Write 100-150 words. Reference key evidence from both cases. State which side has stronger evidence support.
        """
        output_format = """
    Output MUST be a JSON object:
    {
      "for_case": "...",
      "against_case": "...",
      "verdict": "..."
    }
        """

    prompt = f"""
    You are a Senior Fact-Check Analyst producing a balanced, evidence-based analysis.
    
    Topic: "{topic}"
    Stance Preference: {stance_preference.upper()} (Analyze only the requested sides plus the verdict)
    
    {research_section}
    
    {sections_instruction}
    
    CRITICAL RULES FOR CITATIONS & FACTUAL DEPTH:
    • Provide specific facts, figures, dates, and statistics. Avoid vague summaries.
    • When asserting facts from the research evidence, cite bracketed numbers [1], [2] and list the corresponding references at the bottom of the section under "References:".
    • Do NOT invent facts or sources.
    
    {output_format}
    """
    
    try:
        response_text = generate_content_with_retry("groq/compound-mini", prompt, temperature=0.3, json_mode=True, provider=provider, custom_model=custom_model)
        result = clean_and_parse_json(response_text)
        if not isinstance(result, dict):
            result = {}
            
        # Format and deduplicate each section
        for k in ["for_case", "against_case", "verdict"]:
            if k in result and isinstance(result[k], str):
                result[k] = format_and_dedup_turn(result[k])
        
        # Ensure fallback keys are populated to avoid frontend breakdown
        if stance_preference == "for" or stance_preference == "both":
            if "for_case" not in result or not result["for_case"]:
                result["for_case"] = f"Key evidence supporting '{topic}' emphasizes technological advancement, public benefits, and efficiency gains documented across industry studies."
        if stance_preference == "against" or stance_preference == "both":
            if "against_case" not in result or not result["against_case"]:
                result["against_case"] = f"Key counterarguments regarding '{topic}' highlight implementation complexities, financial costs, and regulatory trade-offs identified by analysts."
        if "verdict" not in result or not result["verdict"]:
            result["verdict"] = f"A balanced assessment of '{topic}' indicates valid evidentiary points on both sides, requiring careful policy and practical consideration."
            
        return result
    except Exception as e:
        print(f"Error generating factcheck analysis: {e}")
        return {
            "for_case": f"Proponents of '{topic}' present arguments centered on societal advancement, data-driven outcomes, and operational benefits.",
            "against_case": f"Critics of '{topic}' raise considerations regarding economic barriers, scalability concerns, and alternative approaches.",
            "verdict": f"The overall evidence regarding '{topic}' demonstrates nuanced perspectives from both supporters and critics."
        }


# ─── Claim Extraction ────────────────────────────────────────

def extract_claims(turn_content: str, provider: str = "gemini", custom_model: str = "") -> list[dict]:
    """
    Extracts objectively checkable claims from a turn's content.
    Also extracts any inline cited URLs associated with each claim.
    """
    if MOCK_MODE:
        claims = []
        sentences = re.split(r'(?<=[.!?])\s+', turn_content)
        for s in sentences:
            links = re.findall(r'\[([^\]]+)\]\(([^)]+)\)', s)
            if links:
                clean_text = re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', s).strip()
                claims.append({"claim_text": clean_text, "cited_url": links[0][1]})
            elif any(char.isdigit() for char in s):
                claims.append({"claim_text": s.strip()})
        return claims

    prompt = f"""
    You are a factual claim extraction agent.
    Analyze the following statement from a debater:
    ---
    "{turn_content}"
    ---
    
    Your task:
    1. Identify and extract only the objectively checkable factual claims (dates, historical events, statistics, numbers, scientific statements, official declarations).
    2. Ignore subjective/opinion statements, interpretations, value judgments, or rhetoric.
    3. For each claim, rewrite it as a short, clear, self-contained sentence. Replace pronouns with actual subjects.
    4. If the claim has an inline citation link like [Source](URL), extract that URL as "cited_url".
    5. Extract at most 4 of the most critical and prominent checkable factual claims. If there are fewer, extract only those.
    
    Output MUST be a JSON object:
    {{
      "claims": [
        {{"claim_text": "extracted checkable claim 1", "cited_url": "https://example.com/article" }},
        {{"claim_text": "extracted checkable claim 2" }}
      ]
    }}
    If there are no factual claims, return: {{"claims": []}}.
    """
    try:
        response_text = generate_content_with_retry("llama-3.1-8b-instant", prompt, temperature=0.1, json_mode=True, provider=provider, custom_model=custom_model)
        parsed = clean_and_parse_json(response_text)
        raw_list = []
        if isinstance(parsed, dict):
            if "claims" in parsed and isinstance(parsed["claims"], list):
                raw_list = parsed["claims"]
            else:
                for val in parsed.values():
                    if isinstance(val, list):
                        raw_list = val
                        break
        elif isinstance(parsed, list):
            raw_list = parsed

        # Deduplicate claims to prevent repetitive or paraphrased claims
        unique_claims = []
        seen_keys = set()
        for item in raw_list:
            if not isinstance(item, dict) or not item.get("claim_text"):
                continue
            text = item["claim_text"].strip()
            norm_key = re.sub(r'[^a-z0-9]', '', text.lower())[:50]
            if norm_key and norm_key not in seen_keys and len(unique_claims) < 3:
                seen_keys.add(norm_key)
                unique_claims.append({
                    "claim_text": text,
                    "cited_url": item.get("cited_url")
                })
        return unique_claims
    except Exception as e:
        print(f"Error extracting claims: {e}")
        return []

